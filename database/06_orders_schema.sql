CREATE TABLE ORDERS (
    ORDER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CUSTOMER_ID NUMBER NOT NULL,
    SHIPPING_ADDRESS_ID NUMBER NOT NULL,
    ORDER_DATE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    ORDER_STATUS VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    TOTAL_AMOUNT NUMBER(12,2) DEFAULT 0 NOT NULL,

    CONSTRAINT PK_ORDERS
        PRIMARY KEY (ORDER_ID),

    CONSTRAINT FK_ORDERS_CUSTOMER
        FOREIGN KEY (CUSTOMER_ID)
        REFERENCES CUSTOMER(CUSTOMER_ID),

    CONSTRAINT FK_ORDERS_ADDRESS
        FOREIGN KEY (SHIPPING_ADDRESS_ID)
        REFERENCES ADDRESS(ADDRESS_ID),

    CONSTRAINT CK_ORDERS_STATUS
        CHECK (ORDER_STATUS IN (
            'PENDING',
            'CONFIRMED',
            'PROCESSING',
            'SHIPPED',
            'DELIVERED',
            'CANCELLED'
        )),

    CONSTRAINT CK_ORDERS_TOTAL
        CHECK (TOTAL_AMOUNT >= 0)
);