-- ============================================================
-- VendorVerse
-- Shared Database Schema
-- Oracle Database
-- ============================================================

-- ============================================================
-- 1. APP_ROLE
-- Stores the roles available in VendorVerse.
-- ============================================================

CREATE TABLE APP_ROLE (
    ROLE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ROLE_NAME VARCHAR2(30) NOT NULL,
    DESCRIPTION VARCHAR2(200),

    CONSTRAINT PK_APP_ROLE PRIMARY KEY (ROLE_ID),
    CONSTRAINT UQ_APP_ROLE_NAME UNIQUE (ROLE_NAME)
);


-- ============================================================
-- 2. APP_USER
-- Stores login/account information.
-- Customer profile information will be stored separately.
-- ============================================================

CREATE TABLE APP_USER (
    USER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ROLE_ID NUMBER NOT NULL,
    USERNAME VARCHAR2(50) NOT NULL,
    EMAIL VARCHAR2(100) NOT NULL,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_APP_USER PRIMARY KEY (USER_ID),

    CONSTRAINT FK_APP_USER_ROLE
        FOREIGN KEY (ROLE_ID)
        REFERENCES APP_ROLE(ROLE_ID),

    CONSTRAINT UQ_APP_USER_USERNAME UNIQUE (USERNAME),

    CONSTRAINT UQ_APP_USER_EMAIL UNIQUE (EMAIL),

    CONSTRAINT CK_APP_USER_STATUS
        CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);


-- ============================================================
-- 3. CATEGORY
-- Stores product categories.
-- ============================================================

CREATE TABLE CATEGORY (
    CATEGORY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CATEGORY_NAME VARCHAR2(100) NOT NULL,
    DESCRIPTION VARCHAR2(255),
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,

    CONSTRAINT PK_CATEGORY PRIMARY KEY (CATEGORY_ID),

    CONSTRAINT UQ_CATEGORY_NAME UNIQUE (CATEGORY_NAME),

    CONSTRAINT CK_CATEGORY_STATUS
        CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);


-- ============================================================
-- 4. PRODUCT
-- Shared product information used by Sales and Inventory.
-- ============================================================

CREATE TABLE PRODUCT (
    PRODUCT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CATEGORY_ID NUMBER NOT NULL,
    SKU VARCHAR2(50) NOT NULL,
    PRODUCT_NAME VARCHAR2(150) NOT NULL,
    DESCRIPTION VARCHAR2(500),
    PRICE NUMBER(10,2) NOT NULL,
    REORDER_LEVEL NUMBER(10) DEFAULT 0 NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_PRODUCT PRIMARY KEY (PRODUCT_ID),

    CONSTRAINT FK_PRODUCT_CATEGORY
        FOREIGN KEY (CATEGORY_ID)
        REFERENCES CATEGORY(CATEGORY_ID),

    CONSTRAINT UQ_PRODUCT_SKU UNIQUE (SKU),

    CONSTRAINT CK_PRODUCT_PRICE
        CHECK (PRICE >= 0),

    CONSTRAINT CK_PRODUCT_REORDER_LEVEL
        CHECK (REORDER_LEVEL >= 0),

    CONSTRAINT CK_PRODUCT_STATUS
        CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);