CREATE TABLE ADDRESS (
    ADDRESS_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CUSTOMER_ID NUMBER NOT NULL,
    ADDRESS_LINE VARCHAR2(255) NOT NULL,
    CITY VARCHAR2(100) NOT NULL,
    STATE VARCHAR2(100) NOT NULL,
    PINCODE VARCHAR2(10) NOT NULL,
    ADDRESS_TYPE VARCHAR2(20) DEFAULT 'HOME' NOT NULL,
    IS_DEFAULT CHAR(1) DEFAULT 'N' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_ADDRESS
        PRIMARY KEY (ADDRESS_ID),

    CONSTRAINT FK_ADDRESS_CUSTOMER
        FOREIGN KEY (CUSTOMER_ID)
        REFERENCES CUSTOMER(CUSTOMER_ID),

    CONSTRAINT CK_ADDRESS_TYPE
        CHECK (ADDRESS_TYPE IN ('HOME', 'WORK', 'OTHER')),

    CONSTRAINT CK_ADDRESS_DEFAULT
        CHECK (IS_DEFAULT IN ('Y', 'N'))
);