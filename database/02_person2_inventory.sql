-- VendorVerse: Inventory and Supply Chain
-- Table 1: Warehouse master data

CREATE TABLE WAREHOUSE (
    WAREHOUSE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    WAREHOUSE_CODE VARCHAR2(20) NOT NULL,
    WAREHOUSE_NAME VARCHAR2(100) NOT NULL,
    ADDRESS VARCHAR2(255) NOT NULL,
    CITY VARCHAR2(100) NOT NULL,
    STATE VARCHAR2(100) NOT NULL,
    POSTAL_CODE VARCHAR2(10),
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_WAREHOUSE
        PRIMARY KEY (WAREHOUSE_ID),

    CONSTRAINT UQ_WAREHOUSE_CODE
        UNIQUE (WAREHOUSE_CODE),

    CONSTRAINT CK_WAREHOUSE_STATUS
        CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);
